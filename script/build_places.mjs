// Generates the place list for offline address lookup (public/data/places_de.tsv).
//   curl -O https://download.geonames.org/export/dump/DE.zip && unzip DE.zip
//   node script/build_places.mjs /path/to/DE.txt
// Source: GeoNames (https://www.geonames.org), license CC BY 4.0.
// Keeps populated places and localities (class P), without historical/abandoned ones.
import fs from 'node:fs'

const source = process.argv[2]
if (!source) throw new Error('Specify the path to DE.txt')
const skip = new Set(['PPLH', 'PPLQ', 'PPLW', 'PPLCH'])
const rows = []
for (const line of fs.readFileSync(source, 'utf8').split('\n')) {
  const c = line.split('\t')
  if (c[6] !== 'P' || skip.has(c[7])) continue
  const name = c[1].replace(/\s+/g, ' ').trim()
  if (!name) continue
  // name, latitude, longitude (5 decimals ≈ 1 m), population (0 = unknown)
  rows.push(`${name}\t${Number(c[4]).toFixed(5)}\t${Number(c[5]).toFixed(5)}\t${Number(c[14]) || 0}`)
}
fs.mkdirSync('public/data', { recursive: true })
fs.writeFileSync('public/data/places_de.tsv', `# GeoNames (geonames.org), CC BY 4.0 – generated by script/build_places.mjs\n${rows.join('\n')}\n`)
console.log(`${rows.length} places → public/data/places_de.tsv`)
